const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const exportsObject = {}
vm.runInNewContext(ts.transpileModule(fs.readFileSync('electron/main/ai-requests.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exportsObject, AbortController })
const registry = new exportsObject.AiRequestRegistry()
assert.throws(() => registry.begin(1, ''), /ID 无效/)
const first = registry.begin(1, 'same'), second = registry.begin(2, 'same')
assert.throws(() => registry.begin(1, 'same'), /仍在处理中/)
registry.abort(1, 'same')
assert.equal(first.signal.aborted, true)
assert.equal(second.signal.aborted, false)
assert.throws(() => registry.begin(1, 'same'), /仍在处理中/, 'abort does not finish cleanup')
registry.release(1, 'same', first)
const replacement = registry.begin(1, 'same')
registry.release(1, 'same', first)
registry.abort(1, 'same')
assert.equal(replacement.signal.aborted, true, 'old cleanup must not release replacement')
const extra = registry.begin(2, 'extra')
registry.abortOwner(2)
assert.equal(second.signal.aborted, true)
assert.equal(extra.signal.aborted, true)
registry.release(2, 'same', second); registry.release(2, 'extra', extra)
registry.release(1, 'same', replacement)
assert.equal(registry.begin(2, 'extra').signal.aborted, false, 'finished owner can start cleanly')
console.log('AI requests: ownership, duplicate IDs, cancellation reservation, late cleanup and owner shutdown PASS')
